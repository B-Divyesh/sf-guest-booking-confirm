import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';

const base = process.env.QA_BASE;
if (!base) throw new Error('QA_BASE is required');
const owner = 'verification-10-ui-owner';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await context.newPage();
const consoleErrors = [];
const pageErrors = [];
page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()); });
page.on('pageerror', error => pageErrors.push(String(error)));
await page.addInitScript(ownerId => sessionStorage.setItem('gbc_test_owner_oid', ownerId), owner);

const result = {};
await page.goto(`${base}/manage`, { waitUntil: 'networkidle' });
result.ownerEmptyStart = await page.getByRole('heading', { name: 'Set up your booking desk' }).isVisible();
await page.getByLabel('Business name').fill('UI Verification Studio');
await page.getByLabel('Service name').fill('Planning session');
await page.getByLabel('Business timezone').fill('UTC');
await page.getByLabel('Monday opens').fill('17:00');
await page.getByLabel('Monday closes').fill('09:00');
await page.getByRole('button', { name: 'Open my booking desk' }).click();
result.invalidHoursMessage = await page.getByRole('alert').textContent();
await page.getByLabel('Monday opens').fill('09:00');
await page.getByLabel('Monday closes').fill('17:00');
await page.getByRole('button', { name: 'Open my booking desk' }).click();
await page.getByRole('heading', { name: 'Booking signals', exact: true }).waitFor();
result.ownerEmptyQueue = await page.getByText('No booking signals yet').isVisible();

await page.route('**/api/public/settings', route => route.abort('internetdisconnected'));
await page.goto(`${base}/`);
await page.getByRole('heading', { name: 'We couldn’t open the booking desk' }).waitFor();
result.offlineMessage = await page.locator('.error-panel').textContent();
await page.unroute('**/api/public/settings');
await page.getByRole('button', { name: 'Try again' }).click();
await page.getByRole('heading', { name: /Ask for a time/ }).waitFor();
result.offlineRecovered = true;

await page.getByRole('button', { name: /Send time request/ }).click();
result.requiredMessage = await page.getByRole('alert').textContent();
await page.locator('input[name="starts_at"]').first().check();
await page.getByLabel('Full name').fill('Recovery Guest');
await page.getByLabel('Email').fill('not-an-email');
await page.getByRole('checkbox', { name: /I agree/ }).check();
await page.getByRole('button', { name: /Send time request/ }).click();
result.invalidEmailMessage = await page.getByRole('alert').textContent();
await page.getByLabel('Email').fill('recovery@example.test');
await page.getByRole('button', { name: /Send time request/ }).click();
await page.getByRole('heading', { name: 'Request received' }).waitFor();
const guestUrl = page.url();
result.requestState = await page.getByRole('heading', { level: 1 }).textContent();

const headers = { 'x-test-oid': owner, 'x-forwarded-for': 'verification-10-ui-owner' };
let ownerList = await context.request.get(`${base}/api/owner/bookings`, { headers });
let booking = (await ownerList.json()).bookings[0];
result.approval = (await context.request.patch(`${base}/api/owner/bookings/${booking.id}/approve`, { headers })).status();
await page.goto(guestUrl);
await page.getByRole('heading', { name: 'Ready to confirm' }).waitFor();
await page.getByRole('button', { name: 'Confirm this time' }).focus();
await page.keyboard.press('Enter');
await page.getByRole('heading', { name: 'Confirmed', exact: true }).waitFor();
result.confirmedByKeyboard = true;
const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('link', { name: /Add to calendar/ }).click()]);
result.calendarDownload = download.suggestedFilename();

await page.getByRole('button', { name: 'Request another time' }).click();
await page.locator('#reschedule-form input[name="starts_at"]').first().check();
await page.getByRole('button', { name: 'Send new time request' }).click();
await page.getByRole('heading', { name: 'New time requested' }).waitFor();
result.rescheduleState = await page.getByRole('heading', { level: 1 }).textContent();
ownerList = await context.request.get(`${base}/api/owner/bookings`, { headers });
booking = (await ownerList.json()).bookings.find(item => item.id === booking.id);
result.rescheduleApproval = (await context.request.patch(`${base}/api/owner/bookings/${booking.id}/approve`, { headers })).status();
await page.goto(`${base}/manage`);
await page.getByRole('button', { name: 'Mark reminder sent' }).click();
await page.getByText(/Reminder recorded/).waitFor();
result.reminderRecordedInOwnerUI = true;
await page.goto(guestUrl);
await page.getByRole('button', { name: 'Confirm this time' }).click();
await page.getByRole('heading', { name: 'Confirmed', exact: true }).waitFor();
await page.getByRole('button', { name: 'Cancel booking' }).click();
result.cancelPrompt = await page.locator('.inline-confirm').textContent();
await page.getByRole('button', { name: 'Yes, cancel booking' }).click();
await page.getByRole('heading', { name: 'Cancelled' }).waitFor();
result.cancelledState = await page.getByRole('heading', { level: 1 }).textContent();
const axe = await new AxeBuilder({ page }).analyze();
result.finalAxeSeriousCritical = axe.violations.filter(item => ['serious', 'critical'].includes(item.impact || '')).map(item => item.id);

await page.goto(`${base}/b/invalid-private-link`);
await page.getByRole('heading', { name: 'We couldn’t open the booking desk' }).waitFor();
result.invalidLinkRecovery = await page.locator('.error-panel').textContent();
result.consoleErrors = consoleErrors;
result.pageErrors = pageErrors;
console.log(JSON.stringify(result, null, 2));
await browser.close();
